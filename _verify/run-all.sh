#!/bin/bash
# 运行离线产物核验。
# 用法：bash _verify/run-all.sh
# 需要 python3 和 ../../ghostlock/work/ 下的官方镜像样本；缺少样本时仅运行产物检查。

set -u
cd "$(dirname "$0")" || exit 1

SAMPLES="../../ghostlock/work"
PY=python3
command -v $PY >/dev/null || PY=python

echo "================================================================"
echo "  交付产物离线核验"
echo "================================================================"
$PY ../tools/inspect-artifact.py iris
echo
$PY ../tools/inspect-artifact.py apu

if [ ! -f "$SAMPLES/offmods-iris.tar.gz" ]; then
  echo
  echo "!! 找不到官方镜像样本（$SAMPLES/offmods-iris.tar.gz）"
  echo "   跳过节区、配置与模块集对照。"
  exit 0
fi

echo
echo "================================================================"
echo "  ① ELF 节区名对照（配置保真度最强的证据）"
echo "================================================================"
$PY secnames.py

echo
echo "================================================================"
echo "  ② 配置逐符号对照"
echo "================================================================"
$PY cfg_vs_official.py

echo
echo "================================================================"
echo "  ③ 模块集对照"
echo "================================================================"
$PY modset2.py

echo
echo "================================================================"
echo "  ④ 缺失模块定性（内建 vs 真实缺失）"
echo "================================================================"
$PY classify.py

echo
echo "================================================================"
echo "  ⑤ 承载功能的符号逐项核对"
echo "================================================================"
$PY key_symbols.py

echo
echo "================================================================"
echo "  ⑥ 差异缺口汇总"
echo "================================================================"
$PY gap.py

echo
echo "================================================================"
echo "  ⑦ 文档与产物一致性交叉核对（104 项断言）"
echo "================================================================"
$PY crosscheck.py

echo
echo "================================================================"
echo "  ⑧ 文档数字一致性扫描"
echo "================================================================"
$PY doc_numbers.py

echo
echo "================================================================"
echo "  ⑨ PE 节区 vs EFI_MIXED 因果核对"
echo "================================================================"
$PY pe_vs_efimixed.py

echo
echo "================================================================"
echo "  ⑩ KernelSU 功能标记分布（BTF 影响定性）"
echo "================================================================"
$PY ksu_buckets.py

echo
echo "全部完成。数字应与 FIDELITY.md 一致。"
echo "crosscheck.py 的退出码即总体结论（0 = 全部断言通过）。"
